#!/usr/bin/env python3
"""Builds the single-file distribution of libcui-widget.

    python3 tools/amalgamate.py [OUTDIR]        (default: build/amalgamation)

Mirrors CUI's own tools/amalgamate.py, scaled to this library. It writes:

    cuiw.h        the public C ABI, verbatim (it is already one self-contained
                  header: system includes only, no local includes to inline).
    cuiw.cpp      every internal header and both source files inlined into one
                  translation unit. Compile it with your program as C++20 and
                  link libcui — the same cui.h/cui.c pair CUI's amalgamator
                  emits. No CMake needed.

Unlike CUI, this library is not dependency-free and cannot be: its whole job is
to draw through libcui. So the drop-in story is "four files, two of them CUI's":

    cui.h + cui.c     from CUI (python3 tools/amalgamate.py in the CUI checkout)
    cuiw.h + cuiw.cpp from here

Compile cuiw.cpp as C++20; cui.c as C (on macOS as Objective-C, per CUI's own
note, or define CUI_NO_APP). Every local #include is inlined once; system and
<cui/...> includes stay as they are. All internal headers use #pragma once, so
inlining them once per file in include order is safe.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE_DIRS = [os.path.join(ROOT, "include"), os.path.join(ROOT, "src")]
LOCAL = re.compile(r'^\s*#\s*include\s+"([^"]+)"')

PUBLIC_HEADER = "include/cuiw.h"
SOURCES = ["src/cuiw.cpp", "src/cui_renderer.cpp"]


class Emitter:
    """Writes files, inlining local #includes once each (dedup by resolved path)."""

    def __init__(self):
        self.out = []
        self.seen = set()

    def __call__(self, text):
        self.out.append(text)

    def resolve(self, name, here):
        for base in [os.path.dirname(here)] + INCLUDE_DIRS:
            p = os.path.normpath(os.path.join(base, name))
            if os.path.isfile(p):
                return p
        return None

    def file(self, rel_or_abs):
        path = rel_or_abs if os.path.isabs(rel_or_abs) else os.path.join(ROOT, rel_or_abs)
        path = os.path.normpath(path)
        if path in self.seen:
            return
        self.seen.add(path)
        rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
        self.out.append(f"\n/* ==== {rel} ==== */\n")
        with open(path, encoding="utf-8") as f:
            for line in f:
                # Drop the #pragma once — the amalgamated file is included once
                # by construction, and it is meaningless outside a real header.
                if line.strip() == "#pragma once":
                    continue
                m = LOCAL.match(line)
                target = m and self.resolve(m.group(1), path)
                if target:
                    self.file(target)
                else:
                    self.out.append(line)
        if not self.out[-1].endswith("\n"):
            self.out.append("\n")

    def text(self):
        return "".join(self.out)


def version():
    with open(os.path.join(ROOT, "CMakeLists.txt"), encoding="utf-8") as f:
        m = re.search(r"project\(\s*cui-widget", f.read(), re.I)
    v = "unknown"
    for line in open(os.path.join(ROOT, "src/cuiw.cpp"), encoding="utf-8"):
        m = re.search(r'cuiw_version\(void\)\s*\{\s*return\s*"([^"]+)"', line)
        if m:
            v = m.group(1)
            break
    return v


def banner(what):
    return (f"/* libcui-widget {version()}, {what}. Generated by tools/amalgamate.py from the\n"
            " * sources in this repository; edit those, not this file. Draws through CUI\n"
            " * (https://github.com/yappologistic/CUI) — build CUI's own cui.h + cui.c\n"
            " * alongside this. */\n")


def build_header():
    e = Emitter()
    e.file(PUBLIC_HEADER)
    return e.text()


def build_source():
    e = Emitter()
    for rel in SOURCES:
        e.file(rel)
    return rewrite_cui_includes(e.text())


def rewrite_cui_includes(text):
    """Point the drop-in source at CUI's flat amalgamated cui.h.

    In the CMake/tree build the sources include <cui/cui.h> and
    <cui/cui_render.h>. CUI's own amalgamator merges all three of its public
    headers into one flat cui.h, so the drop-in form includes "cui.h" once.
    Rewrite to match, the way CUI's docs tell you to for its single-file form.
    """
    return re.sub(r'^(\s*)#\s*include\s+<cui/[a-z_]+\.h>.*$',
                  r'\1#include "cui.h"',
                  text, flags=re.MULTILINE)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "amalgamation")
    os.makedirs(out, exist_ok=True)

    header = build_header()
    source = build_source()

    with open(os.path.join(out, "cuiw.h"), "w", encoding="utf-8") as f:
        f.write(banner("public C ABI") + header)
    with open(os.path.join(out, "cuiw.cpp"), "w", encoding="utf-8") as f:
        f.write(banner("every internal header and source file in one translation unit"))
        # The public header is NOT inlined here separately: the sources include
        # "cuiw.h" themselves, and the emitter dedups by path, so it is inlined
        # exactly once below. #pragma once is stripped, which is safe because the
        # file is emitted once and is not itself a header.
        f.write("\n/* ---- implementation (public header + sources, inlined) ---- */\n"
                + source)

    for name in ("cuiw.h", "cuiw.cpp"):
        p = os.path.join(out, name)
        print(f"{p}  {os.path.getsize(p)} bytes")


if __name__ == "__main__":
    main()
